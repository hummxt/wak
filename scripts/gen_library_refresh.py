def main() -> None:
    ROOT.mkdir(parents=True, exist_ok=True)
    # Remove refreshed categories' old files (keep still/coolors/shader/etc).
    for path in list(ROOT.glob("*.json")):
        name = path.name
        if any(name.startswith(prefix) for prefix in REMOVE_PREFIXES):
            path.unlink()
            print("remove", name)
        if name == "soft-motion.json":
            path.unlink()
            print("remove", name)
        if name in {"noise-field.json", "liquid-bloom.json", "liquid-mercury.json", "aurora-veil.json", "aurora-boreal.json", "aurora-violet.json"}:
            if path.exists():
                path.unlink()
                print("remove", name)

    for preset in PRESETS:
        write(preset)
    print(f"wrote {len(PRESETS)} presets")


if __name__ == "__main__":
    main()
