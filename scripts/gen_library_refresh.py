def write(preset: dict) -> None:
    path = ROOT / f"{preset['id']}.json"
    path.write_text(json.dumps(preset, indent=2) + "\n", encoding="utf-8")
    print("write", path.name)


def p(
    id_: str,
    name: str,
    category: str,
    shader: str,
    description: str,
    colors: list,
    **kw,
) -> dict:
    out = {
        "id": id_,
        "name": name,
        "category": category,
        "shader": shader,
        "description": description,
        "thumbnail": f"thumbnails/{id_}.png",
        "colorA": colors[0],
        "colorB": colors[1],
        "colorC": colors[2],
        "colorD": colors[3],
    }
    out.update(kw)
    return out


